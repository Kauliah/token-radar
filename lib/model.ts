// Token Radar, model radar-2: one sealed snapshot in, one ranked board out.
//
// The board ranks every protocol that records no token and is not a wrapped,
// staked or bridged product of a token that already trades. The watchlist the
// house drew (TVL at or above the $50M floor) is the floor, never the ceiling:
// the board adds every other rankable pre-token protocol below that floor, so
// the early radar is the whole pre-token universe the snapshot can see below
// the line. A protocol above the floor that the watchlist leaves out stays
// out: the house's rule kept it off for a reason the snapshot's ten fields
// cannot see (a parent protocol).
//
// Implied value is built only from the snapshot's own figures, in four
// factors that the dashboard shows per row:
//
//   multiple   the category's own market multiple: the median market-cap /
//              TVL ratio of the snapshot's live-token protocols in the same
//              category (at least 3 of them), else the median ratio over all
//              live-token protocols; clamped to [0.05, 0.60]. A category with
//              one or two live comparables borrows the whole-market median
//              instead of trusting a single ratio. The multiples are computed
//              from the snapshot at run time, never written in by hand.
//   growth     1 + clamp(change_7d, -60, 120) / 100 x 0.5
//   maturity   0.6 + min(age_days, 1095) / 1095 x 0.4, where age_days is the
//              time since DefiLlama first listed the protocol: how long it
//              has run with no token on record. Unknown listing date: 365.
//   chains     1 + 0.04 x min(chains - 1, 5): a protocol live on more chains
//              has a wider distribution surface for a launch.
//
//   implied = max(1, round(tvl_usd x multiple x growth x maturity x chains))
//
// No protocol name is ever special-cased: the same function scores every
// row, and the dashboard recomputes each row from the same figures. Live
// token protocols are never ranked: they are set aside in the Live view with
// their market caps, which are facts, not a model.

/** One protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

